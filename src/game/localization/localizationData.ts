export interface TranslationLookupResult {
  text: string;
  status: 'ok' | 'fallback_en' | 'missing_key';
}

export function hasTranslationKey(key: string): boolean {
  return Boolean(LOCALIZATION_TABLE[key]);
}

/**
 * Controlled Fallback Chain:
 *   Current Language -> Default Language (en-US) -> Safe Placeholder ([Missing Localization: key])
 */
export function resolveTranslation(key: string, locale: LocaleId): TranslationLookupResult {
  const entry = LOCALIZATION_TABLE[key];
  if (!entry) {
    return {
      text: `[Missing Localization: ${key}]`,
      status: 'missing_key',
    };
  }
  const localized = entry[locale];
  if (typeof localized === 'string' && localized.trim().length > 0) {
    return { text: localized, status: 'ok' };
  }
  const fallbackEn = entry['en-US'];
  if (typeof fallbackEn === 'string' && fallbackEn.trim().length > 0) {
    return { text: fallbackEn, status: 'fallback_en' };
  }
  return {
    text: `[Missing Localization: ${key}]`,
    status: 'missing_key',
  };
}

export function lookupTranslation(key: string, locale: LocaleId): string {
  return resolveTranslation(key, locale).text;
}
