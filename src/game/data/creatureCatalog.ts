export function isCreatureAllowedInHabitat(
  creature: CreatureData,
  habitatId: HabitatId
): boolean {
  if (!creature.allowedHabitats || creature.allowedHabitats.length === 0) {
    return true;
  }
  return creature.allowedHabitats.includes(habitatId);
}
